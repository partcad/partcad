def test_document_markdown():
    """Every kind of block, written down as markdown"""
    document = pc_document.Document(
        title="widget",
        pages=[
            pc_document.Page(
                blocks=[
                    pc_document.Heading("widget", level=1),
                    pc_document.Paragraph("A widget."),
                    pc_document.Properties([("Package", "`//pkg`")]),
                    pc_document.Heading("//other", level=3, url="../other/README.md"),
                    pc_document.Table(
                        columns=["Part", "Count", "Description"],
                        aligns=["left", "right", "left"],
                        rows=[["bolt", 2, "a | b\nc"]],
                    ),
                    pc_document.ImageRow([pc_document.Image(file="/tmp/widget.svg", src="./widget.svg")]),
                    pc_document.LinkList([("PartCAD", "https://partcad.org/")]),
                ]
            )
        ],
        footer=pc_document.GENERATED_BY,
    )

    lines = pc_document.render_markdown(document)

    assert lines[0] == "# widget"
    assert "A widget." in lines
    assert "Package: `//pkg`" in lines
    assert "### [//other](../other/README.md)" in lines
    assert "| Part | Count | Description |" in lines
    assert "| --- | ---: | --- |" in lines
    # A cell keeps the table one row per line: no bare pipes, no newlines.
    assert "| bolt | 2 | a \\| b<br/>c |" in lines
    assert '<img src="./widget.svg" alt="" style="%s">' % pc_document.MARKDOWN_IMAGE_STYLE in lines
    assert "- [PartCAD](https://partcad.org/)" in lines
    assert lines[-1] == "*Generated by [PartCAD](https://partcad.org/)*"


def test_document_html():
    """The HTML document is one file that shows one page at a time"""
    document = pc_document.Document(
        title="widget & co",
        pages=[
            pc_document.Page(title="Title", blocks=[pc_document.Heading("widget & co")]),
            pc_document.Page(title="Links", blocks=[pc_document.LinkList([("PartCAD", "https://partcad.org/")])]),
        ],
        footer=pc_document.GENERATED_BY,
    )

    html = pc_document.render_html(document)

    assert "<title>widget &amp; co</title>" in html
    assert '<section class="page" id="page-1" data-title="Title">' in html
    assert '<section class="page" id="page-2" data-title="Links">' in html
    assert "<h1>widget &amp; co</h1>" in html
    assert '<a href="https://partcad.org/">PartCAD</a>' in html
    # The pages are flipped through rather than scrolled.
    assert 'id="prev"' in html and 'id="next"' in html
    assert "ArrowLeft" in html and "ArrowRight" in html


def test_document_html_inlines_images():
    """An HTML document carries its illustrations rather than pointing at them"""
    with tempfile.TemporaryDirectory() as directory:
        path = os.path.join(directory, "widget.svg")
        with open(path, "w") as f:
            f.write('<svg xmlns="http://www.w3.org/2000/svg"/>')

        document = pc_document.Document(
            pages=[pc_document.Page(blocks=[pc_document.ImageRow([pc_document.Image(file=path)])])]
        )
        html = pc_document.render_html(document)

    assert "data:image/svg+xml;base64," in html
    # The file it was made from is gone by now, and the document still has it.
    assert path not in html


def test_document_to_data_is_plain():
    """The PDF renderer is handed plain data, not objects"""
    document = pc_document.Document(
        title="widget",
        pages=[
            pc_document.Page(
                blocks=[
                    pc_document.Heading("widget"),
                    pc_document.Table(columns=["Part"], rows=[["bolt"]]),
                    pc_document.ImageRow([pc_document.Image(file="/tmp/widget.svg", caption="widget")]),
                ]
            )
        ],
    )

    data = pc_document.to_data(document)

    assert data["title"] == "widget"
    blocks = data["pages"][0]["blocks"]
    assert blocks[0] == {"type": "heading", "text": "widget", "level": 1, "url": None}
    assert blocks[1]["rows"] == [["bolt"]]
    assert blocks[2]["images"] == [{"path": "/tmp/widget.svg", "caption": "widget", "alt": ""}]


def test_document_to_data_embeds_images_on_request():
    """A reader with no file system in reach is handed the pictures themselves

    The IDE's viewer is a webview on the other side of a JSON-RPC connection, and
    the illustrations of an instruction book live in a temporary directory that
    is deleted as soon as the document has been built.
    """
    with tempfile.TemporaryDirectory() as directory:
        path = os.path.join(directory, "widget.svg")
        with open(path, "w") as f:
            f.write('<svg xmlns="http://www.w3.org/2000/svg"/>')

        document = pc_document.Document(
            pages=[
                pc_document.Page(
                    blocks=[pc_document.ImageRow([pc_document.Image(file=path, caption="widget", alt="widget")])]
                )
            ]
        )
        data = pc_document.to_data(document, embed_images=True)

    (image,) = data["pages"][0]["blocks"][0]["images"]
    assert image["src"].startswith("data:image/svg+xml;base64,")
    assert image["caption"] == "widget"
    # The file it was made from is gone by now, and the document still has it.
    assert "path" not in image


def test_pdf_table_row_never_outgrows_the_table():
    """A row wider than the table's columns stays on the page

    Every cell has to be drawn, and the row has to keep the width of the table:
    a cell past the right edge of the page is hidden just as surely as one that
    was dropped.
    """
    # 'wrapper_layout', not the wrapper that draws the PDF: the latter imports
    # reportlab, which is installed in the sandbox the PDF is composed in and
    # not on the host the tests run on.
    sys.path.insert(0, os.path.join("partcad", "src", "partcad", "wrappers"))
    import wrapper_layout

    widths, aligns = [100.0, 50.0, 200.0], ["left", "right", "left"]
    total = sum(widths)

    # The usual case is left exactly as it was.
    assert wrapper_layout.fit_row(["a", "b", "c"], widths, aligns) == (widths, aligns)

    for count in (4, 6):
        row = ["cell"] * count
        row_widths, row_aligns = wrapper_layout.fit_row(row, widths, aligns)
        assert len(row_widths) >= count
        assert len(row_aligns) >= count
        assert row_widths == pytest.approx([100.0, 50.0] + [200.0 / (count - 2)] * (count - 2))
        assert sum(row_widths) == pytest.approx(total)


