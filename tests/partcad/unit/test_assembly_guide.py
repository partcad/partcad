def test_guide_requires_an_assy():
    """Only an assembly with declared steps gets an instruction book"""
    with pytest.raises(NotAnAssemblyFileError):
        assembly_guide.check_source(make_assembly(type="file"))
    with pytest.raises(NotAnAssemblyFileError):
        assembly_guide.check_source(make_assembly(type="alias"))

    # No exception: this one is an ASSY and is meant to be built.
    assembly_guide.check_source(make_assembly())


def test_guide_requires_manufacturability():
    """An assembly nobody is meant to build is refused unless asked twice"""
    assembly = make_assembly(manufacturable=False)

    with pytest.raises(NotManufacturableError) as error:
        assembly_guide.check_source(assembly)
    assert "--ignore-manufacturability" in str(error.value)

    assembly_guide.check_source(assembly, ignore_manufacturability=True)


def test_guide_resolves_aliases():
    """An alias is documented as whatever it points at"""
    ctx = pc.init("examples")
    alias = ctx._get_assembly("//produce_assembly_assy:partcad_logo")
    assert alias is not None
    assert alias.config.get("type") == "alias"

    resolved = assembly_guide.resolve_alias(ctx, alias)

    assert resolved.name == "logo"
    assert resolved.config.get("type") == "assy"
    # Which is what makes it documentable at all.
    assembly_guide.check_source(resolved, ignore_manufacturability=True)


