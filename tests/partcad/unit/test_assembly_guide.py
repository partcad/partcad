def test_step_source_looks_through_the_root_container():
    """The container an ASSY file's root node creates is not a sub-assembly

    Every ASSY file holds its items in a container node, so the assembly a
    package declares has a single embedded assembly as its only child. That
    wrapper is the assembly itself under another name.
    """
    inner = make_assembly("outer:None", child=True)
    inner.add(make_assembly("a"), "a")
    inner.add(make_assembly("b"), "b")
    outer = make_assembly("outer")
    outer.add(inner, None)

    assert assembly_guide._step_source(outer) is inner
    # An assembly that holds a single part is not a wrapper around anything.
    assert assembly_guide._step_source(inner) is inner


def test_exploded_location_moves_the_item_along_the_joint():
    """An exploded view holds the item off the joint by the gap it is given"""
    step = assembly_guide.GuideStep(
        number=1,
        item=make_assembly("a"),
        item_name="a",
        location=Location([[1, 2, 3], [0, 0, 1], 0]),
        counterpart=make_assembly("b"),
        counterpart_name="b",
        counterpart_location=Location(),
        direction=(0.0, 0.0, 1.0),
        distance=10.0,
    )

    translation = step.exploded_location().translation

    assert translation == pytest.approx((1.0, 2.0, 13.0))


def test_exploded_is_validated_where_it_is_declared():
    """A gap that is not a number is reported and dropped, not carried onwards

    An ASSY file is not validated against a schema, so this is the only place
    that can tell the reader which file the bad value is in. Left to reach the
    renderer, it would surface as a ValueError naming neither.
    """
    factory = assembly_factory_assy.AssemblyFactoryAssy.__new__(assembly_factory_assy.AssemblyFactoryAssy)
    factory.name = "widget"

    assert factory._exploded_distance(None, "bracket") is None
    assert factory._exploded_distance(30, "bracket") == 30.0
    assert factory._exploded_distance("30", "bracket") == 30.0
    # Neither of these is a distance; the step falls back to the default gap.
    assert factory._exploded_distance("far", "bracket") is None
    assert factory._exploded_distance(True, "bracket") is None


def test_step_description_names_the_ports():
    """A step says what is connected to what"""
    step = assembly_guide.GuideStep(
        number=1,
        item=make_assembly("screw"),
        item_name="screw",
        location=Location(),
        counterpart=make_assembly("bracket"),
        counterpart_name="bracket",
        counterpart_location=Location(),
        connection={"with_port": "thread", "to_port": "hole"},
    )

    assert step.description() == "Connect the thread port of screw to the hole port of bracket."


@pytest.mark.slow
def test_connection_is_recorded_for_connected_items():
    """Placing an item by connecting it records what it was connected to

    Without this, nothing downstream can tell which two items a step joins: the
    resulting placement is just a location like any other.
    """
    ctx = pc.init("examples")
    assembly = ctx._get_assembly("//feature_interface:connect-ports")
    assert assembly is not None
    asyncio.run(assembly.do_instantiate())
    content = assembly_guide._step_source(assembly)

    connections = [child.connection for child in content.children if child.connection]
    assert len(connections) == len(content.children) - 1

    first = connections[0]
    assert first["target"] == "example-bracket"
    assert first["with_port"] and first["to_port"]
    # Where the two ports meet, and which way to pull them apart.
    assert len(first["point"]) == 3
    assert len(first["direction"]) == 3


def test_links_page_points_at_the_package_and_its_suppliers():
    """The closing page links to where the parts came from

    Only to the packages that supply enough of them to be worth a look: whoever
    is assembling this needs to know where to get four of the parts, not which
    package the one bolt came from.
    """
    ctx = pc.init("examples")
    prj = ctx.get_project("//produce_assembly_assy")
    assembly = prj.get_assembly("logo")
    grouped = asyncio.run(assembly.get_bom_grouped_async())

    page = assembly_guide._links_page(prj, assembly, grouped, prj.config_dir)
    items = page.blocks[-1].items
    texts = [text for text, _ in items]

    assert ("PartCAD", pc_document.PARTCAD_URL) in items
    assert any(text.startswith("This assembly: logo") for text in texts)
    assert any(text.startswith("This package: ") for text in texts)
    # Two bones and two head halves come from one package; the single bolt of
    # another one does not earn it a link.
    assert any("produce_part_cadquery_logo (4 parts)" in text for text in texts)
    assert not any("produce_part_step" in text for text in texts)


